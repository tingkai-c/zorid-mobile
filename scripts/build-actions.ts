import { resolve } from 'node:path';

// Hermes does not promise to preserve Function#toString. Ship source compiled on
// the host, including the handler's imports, rather than serializing on-device.
const build = await Bun.build({
  entrypoints: [resolve('src/features/focus-action-entry.ts')],
  target: 'browser', format: 'iife', minify: false,
});
if (!build.success) throw new AggregateError(build.logs, 'Action compilation failed');
const source = `function(args, sdk) {\n${await build.outputs[0].text()}\nreturn globalThis.__zoridFocusAction(args, sdk);\n}`;
const generated = `// Generated by bun run build:actions. Edit focus-action-handler.ts instead.\nexport const focusActionSource = ${JSON.stringify(source)};\n`;
const path = resolve('src/features/focus-actions.generated.ts');
await Bun.write(resolve('build/actions/focus-control.txt'), source);
if (process.argv.includes('--check')) {
  if (await Bun.file(path).text() !== generated) throw new Error('Action bundle is stale. Run bun run build:actions.');
} else await Bun.write(path, generated);
